# majordomus-covers: update
# An adopting clone merges what generators write without a conflict (I4770). `update` declares,
# in the clone only, the two drivers of share/libexec/merge-derived and the paths each takes:
# files the scope's out.generated declares or update writes whole resolve to ours, and every
# tracked document holding a generated region merges the text people wrote three ways while
# each region is taken from ours. What must hold:
#   - two branches that each regenerate the same regions merge clean, the authored edits of
#     both sides survive, and the regions are ours (stale until their generator runs again);
#   - an authored conflict outside the regions is still a conflict, never resolved silently;
#   - a hash-comment block that does not say it is generated merges as text;
#   - nothing tracked changes, and a second update declares nothing new.
. "$ROOT/test/lib.sh"
MAJORDOMUS_SHARE="$ROOT/share"; export MAJORDOMUS_SHARE
git config user.email t@example.invalid; git config user.name t

"$MJ" init >/dev/null
cat > README.md <<'E'
# Title
intro text
<!-- surfaces:begin facts dir=x -->
count: 10
<!-- surfaces:end facts -->
middle
# >>> generated by a tool >>>
gen 1
# <<< generated by a tool <<<
tail
E
cat > notes.md <<'E'
# >>> my own notes >>>
written by a person
# <<< my own notes <<<
E
mkdir -p out && printf 'fingerprint 1\n' > out/index.json
# the adopter declares the directory its generator writes whole
awk '{print} /^  generated:$/ {getline; print "    paths: [\"out/**\"]"; next}' .ai/repo/scope.yaml > scope.new && mv scope.new .ai/repo/scope.yaml
grep -q 'out/\*\*' .ai/repo/scope.yaml || { echo "    the fixture did not declare out/**"; exit 1; }
git add -A >/dev/null && git commit -qm base

expect_exit 0 "$MJ" update
expect_grep '^merge drivers: declared'
tracked_before="$(git status --porcelain)"
attrs="$(git rev-parse --git-common-dir)/info/attributes"
expect_grep '^/README\.md merge=majordomus-regions$' "$attrs"
expect_grep '^/out/\*\* merge=majordomus-derived$' "$attrs"
expect_no_grep 'notes\.md' "$attrs"
[ "$(git config --get merge.majordomus-regions.driver)" = "$ROOT/share/libexec/merge-derived regions %O %A %B %P" ] \
  || { echo "    the regions driver is not declared: $(git config --get merge.majordomus-regions.driver)"; exit 1; }

# a second run declares nothing new, and a dry run says so in update's own words
snap="$(mktemp "${TMPDIR:-/tmp}/mj.4770.XXXXXX")"; cp "$attrs" "$snap"
expect_exit 0 "$MJ" update
expect_grep '^merge drivers: unchanged'
cmp -s "$attrs" "$snap" || { echo "    a second update changed info/attributes"; diff "$snap" "$attrs"; exit 1; }; rm -f "$snap"
expect_exit 0 "$MJ" update --dry-run
expect_grep '^unchanged merge-drivers$'
[ "$(git status --porcelain)" = "$tracked_before" ] || { echo "    update changed a tracked file: $(git status --porcelain)"; exit 1; }
git add -A >/dev/null; git commit -qm bootstrap >/dev/null 2>&1 || true

base="$(git rev-parse --abbrev-ref HEAD)"
# ---------------------------------------------------------------- both sides regenerate
git checkout -qb a
sed -i.bak 's/count: 10/count: 11/; s/gen 1/gen A/; s/intro text/intro text by A/' README.md
printf 'fingerprint A\n' > out/index.json; rm -f README.md.bak
git commit -qam a
git checkout -q "$base"; git checkout -qb b
sed -i.bak 's/count: 10/count: 12/; s/gen 1/gen B/; s/^tail$/tail by B/' README.md
printf 'fingerprint B\n' > out/index.json; printf 'edited by B\n' > notes.md; rm -f README.md.bak
git commit -qam b
git checkout -q a
git merge -q --no-edit b >/dev/null 2>&1 || { echo "    the merge conflicted: $(git status --porcelain)"; git diff; exit 1; }
expect_grep '^intro text by A$' README.md
expect_grep '^tail by B$' README.md
expect_grep '^count: 11$' README.md
expect_grep '^gen A$' README.md
expect_grep '^fingerprint A$' out/index.json
expect_grep '^edited by B$' notes.md

# ---------------------------------------------------------------- an authored conflict stays one
git checkout -q "$base"; git checkout -qb c
sed -i.bak 's/^middle$/middle by C/; s/count: 10/count: 13/' README.md; rm -f README.md.bak; git commit -qam c
git checkout -q "$base"; git checkout -qb d
sed -i.bak 's/^middle$/middle by D/; s/count: 10/count: 14/' README.md; rm -f README.md.bak; git commit -qam d
rc=0; git merge -q --no-edit c >/dev/null 2>&1 || rc=$?
[ "$rc" != 0 ] || { echo "    an authored conflict merged silently"; exit 1; }
expect_grep '^<<<<<<< ' README.md
expect_grep '^count: 14$' README.md
expect_no_grep '^count: 13$' README.md
git merge --abort

# ---------------------------------------------------------------- a person's block of that shape is text
git checkout -q "$base"; git checkout -qb e
printf '# >>> my own notes >>>\nwritten by E\n# <<< my own notes <<<\n' > notes.md; git commit -qam e
git checkout -q "$base"; git checkout -qb f
printf '# >>> my own notes >>>\nwritten by F\n# <<< my own notes <<<\n' > notes.md; git commit -qam f
rc=0; git merge -q --no-edit e >/dev/null 2>&1 || rc=$?
[ "$rc" != 0 ] || { echo "    a hand-written block that only looks like a region was resolved without a conflict"; exit 1; }
git merge --abort
exit 0
