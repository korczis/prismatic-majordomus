//! The version: the one place it is authored, what is derived from that place, what the
//! contract requires next and what the commits imply as evidence, and the one writer that
//! raises it.
//!
//! The product version is authored in exactly one place, the `[package] version` line of
//! the crate manifest ([`MANIFEST`]). Every other statement of it is derived from that line
//! and checked, or is a record of a version that was released:
//!
//! ```text
//!   apps/majordomus-cli/Cargo.toml   authored    the one place; `release bump` writes it
//!   crate::VERSION                   compiled    cargo's CARGO_PKG_VERSION
//!   share/version.txt                projected   `majordomus generate`; bin/majordomus reads it
//!   apps/majordomus-cli/Cargo.lock   derived     cargo's record; the writer keeps it in step
//!   generator stamps, the changelog  generated   `majordomus generate`
//!   .ai/repo/releases/*.yaml         records     the release pipeline, after publication
//!   .ai/manifest.yaml written_for    stamped     `release bump`, once the last release reads it
//! ```
//!
//! Every layer names the tool version it was written for (`init` stamps it, `update`
//! advances it, `doctor` grades it). This repository's layer is written by the version it
//! releases, so [`stamp_layer`] puts that version beside the authority — but only from the
//! release after the one that first reads the key ([`WRITTEN_FOR_READ_SINCE`]): every
//! released tool refuses a manifest key it does not know, and a stamp the installed tool
//! cannot read would refuse this repository to every session running it.
//!
//! The shell tool used to state the version a second time, by hand, because an installed
//! tree has no `Cargo.toml` and the tool cannot read one at run time. It reads
//! [`PROJECTION`] instead: a typed generated artifact that ships in every archive beside the
//! tool, that `generate --check` refuses when it falls behind the manifest, and that nobody
//! edits. [`diagnose`] is what refuses a version anybody writes down by hand where the
//! tool's own files live.
//!
//! One reader of the authority per language: [`declared`] here, `scripts/release-version`
//! in shell. Nothing else parses the manifest for its version.
//!
//! ```
//! use majordomus_cli::release::version::{declared_in, parse_projection, render_projection};
//! // the authority, and the one line the shell tool reads back from its projection of it
//! let authority = declared_in("[package]\nversion = \"0.9.0\"\n").unwrap();
//! assert_eq!(parse_projection(&render_projection(&authority)).as_deref(), Some("0.9.0"));
//! ```

