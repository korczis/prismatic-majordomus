/// How much a set of changes raises a version.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Bump {
    /// Nothing since the last release.
    None,
    /// A fix, or anything that is not a feature.
    Patch,
    /// At least one feature.
    Minor,
    /// At least one breaking change.
    Major,
}

impl Bump {
    /// The word the reports use.
    pub fn as_str(self) -> &'static str {
        match self {
            Bump::None => "none",
            Bump::Patch => "patch",
            Bump::Minor => "minor",
            Bump::Major => "major",
        }
    }

    /// The bump named by a word, for `release bump --minor` and friends.
    pub fn parse(word: &str) -> Option<Bump> {
        match word {
            "major" => Some(Bump::Major),
            "minor" => Some(Bump::Minor),
            "patch" => Some(Bump::Patch),
            "none" => Some(Bump::None),
            _ => None,
        }
    }
}

/// What a set of conventional commits *says about itself*.
///
/// The rule is the conventional-commit rule and nothing more: a breaking change is major, a
/// feature is minor, anything else is patch, and no commits at all is none.
///
/// # This is evidence, not authority
///
/// It used to decide what `release bump` wrote, and that was the defect this subsystem
/// exists to remove. A commit message is a label a person chose, and a capability deleted
/// under a `refactor:` heading was a patch to this function and a broken caller to everyone
/// else. The compatibility level is now measured from the public contract by
/// [`crate::release::compat::analyze`]; this answer is carried beside it as
/// [`crate::release::compat::CommitEvidence`], and when the two disagree the plan says which
/// one understated the change. Nothing decides a version from this alone.
pub fn bump_of(changes: &[Change]) -> Bump {
    if changes.is_empty() {
        return Bump::None;
    }
    if changes.iter().any(|c| c.breaking) {
        return Bump::Major;
    }
    if changes.iter().any(|c| c.kind == ChangeKind::Feat) {
        return Bump::Minor;
    }
    Bump::Patch
}

/// A semantic version, only as much as this needs.
///
/// Ordered by the three numbers, which is what lets the writer refuse a version smaller than
/// the one the contract requires rather than only a *bump* smaller than required.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct Version {
    /// Major.
    pub major: u64,
    /// Minor.
    pub minor: u64,
    /// Patch.
    pub patch: u64,
}

impl Version {
    /// Read `1.2.3`; anything else is `None`.
    pub fn parse(text: &str) -> Option<Version> {
        let mut parts = text.trim().split('.');
        let major = parts.next()?.parse().ok()?;
        let minor = parts.next()?.parse().ok()?;
        let patch = parts.next()?.parse().ok()?;
        if parts.next().is_some() {
            return None;
        }
        Some(Version {
            major,
            minor,
            patch,
        })
    }

    /// This version raised by `bump`.
    ///
    /// Arithmetic and nothing else: zero-major is not special-cased here, because whether a
    /// breaking change below 1.0 costs a major or a minor is a *policy* question and this
    /// repository answers it in exactly one place, [`crate::release::compat::Policy`]. A
    /// second answer here is the shape this subsystem was built to remove.
    pub fn raised(self, bump: Bump) -> Version {
        match bump {
            Bump::None => self,
            Bump::Patch => Version {
                patch: self.patch + 1,
                ..self
            },
            Bump::Minor => Version {
                minor: self.minor + 1,
                patch: 0,
                ..self
            },
            Bump::Major => Version {
                major: self.major + 1,
                minor: 0,
                patch: 0,
            },
        }
    }
}

impl Version {
    /// This version raised by a measured compatibility impact.
    ///
    /// The bridge between the engine's verdict and the arithmetic: the policy has already
    /// decided what a `0.x` breaking change costs, so this only has to apply it.
    ///
    /// ```
    /// use majordomus_cli::release::compat::Impact;
    /// use majordomus_cli::release::version::Version;
    /// let v = Version::parse("0.5.0").unwrap();
    /// assert_eq!(v.raised_to(Impact::Minor).to_string(), "0.6.0");
    /// assert_eq!(v.raised_to(Impact::Major).to_string(), "1.0.0");
    /// assert_eq!(v.raised_to(Impact::None).to_string(), "0.5.0");
    /// ```
    pub fn raised_to(self, impact: crate::release::compat::Impact) -> Version {
        use crate::release::compat::Impact;
        self.raised(match impact {
            Impact::None => Bump::None,
            Impact::Patch => Bump::Patch,
            Impact::Minor => Bump::Minor,
            Impact::Major => Bump::Major,
        })
    }
}

impl std::fmt::Display for Version {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}.{}.{}", self.major, self.minor, self.patch)
    }
}

/// The version the crate manifest declares: the authority.
///
/// The one Rust reader of it. `majordomus generate` asks the same function when it decides
/// whether the executable running is the one the tree declares.
///
/// ```
/// use majordomus_cli::release::version::{declared, MANIFEST};
/// let dir = tempfile::tempdir().unwrap();
/// // No manifest is no version, never a guess.
/// assert_eq!(declared(dir.path()), None);
/// std::fs::create_dir_all(dir.path().join("apps/majordomus-cli")).unwrap();
/// std::fs::write(dir.path().join(MANIFEST), "[package]\nversion = \"0.9.0\"\n").unwrap();
/// assert_eq!(declared(dir.path()).as_deref(), Some("0.9.0"));
/// ```
pub fn declared(root: &Path) -> Option<String> {
    declared_in(&std::fs::read_to_string(root.join(MANIFEST)).ok()?)
}

/// The `[package] version` of a manifest's text.
///
/// The first `version = "..."` inside `[package]`, which is where the manifest puts it: a
/// dependency pinned at a version further down is a different package, a key that merely
/// begins with `version` is a different key, and a trailing comment is not part of the value.
/// Read without a TOML parser, because the value wanted is one quoted scalar in a table whose
/// header is unambiguous, and a dependency to read it would be one this crate argues against.
///
/// ```
/// use majordomus_cli::release::version::declared_in;
/// let manifest = "[package]\nname = \"x\"\nversion = \"1.2.3\"   # bumped\n\n\
///                 [dependencies]\nserde = { version = \"1.2.4\" }\n";
/// assert_eq!(declared_in(manifest).as_deref(), Some("1.2.3"));
/// // outside [package] there is no package version at all
/// assert_eq!(declared_in("[dependencies]\nversion = \"1.0.0\"\n"), None);
/// // a key that only starts with the word is another key
/// assert_eq!(declared_in("[package]\nversioned = \"1.0.0\"\n"), None);
/// ```
pub fn declared_in(manifest: &str) -> Option<String> {
    let mut in_package = false;
    for line in manifest.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_package = line == "[package]";
            continue;
        }
        if !in_package {
            continue;
        }
        let Some(rest) = line.strip_prefix("version") else {
            continue;
        };
        let Some(rest) = rest.trim_start().strip_prefix('=') else {
            continue;
        };
        let rest = rest.trim();
        let value = match rest.strip_prefix('"') {
            Some(quoted) => quoted.split('"').next().unwrap_or_default(),
            None => rest.split('#').next().unwrap_or_default().trim(),
        };
        return (!value.is_empty()).then(|| value.to_string());
    }
    None
}

/// The version the lock file records for this crate.
///
/// Only the entry whose `name` is this crate's: a dependency that happens to be at the same
/// version is a different package and is never read or written here.
///
/// ```
/// use majordomus_cli::release::version::locked;
/// let dir = tempfile::tempdir().unwrap();
/// // No lock file at all is `None`, never a guess.
/// assert_eq!(locked(dir.path()), None);
/// ```
pub fn locked(root: &Path) -> Option<String> {
    let text = std::fs::read_to_string(root.join(LOCK)).ok()?;
    let mut in_package = false;
    for line in text.lines() {
        let line = line.trim();
        if line == "[[package]]" {
            in_package = false;
            continue;
        }
        if line == "name = \"majordomus-cli\"" {
            in_package = true;
            continue;
        }
        if in_package {
            if let Some(rest) = line.strip_prefix("version") {
                return rest.split('"').nth(1).map(|v| v.to_string());
            }
        }
    }
    None
}

/// The body of [`PROJECTION`]: one `version=` line, which `bin/majordomus` reads with shell
/// builtins alone. `majordomus generate` puts its provenance banner above it.
///
/// ```
/// use majordomus_cli::release::version::{parse_projection, render_projection};
/// assert_eq!(render_projection("0.9.0"), "version=0.9.0\n");
/// assert_eq!(parse_projection(&render_projection("0.9.0")).as_deref(), Some("0.9.0"));
/// ```
pub fn render_projection(version: &str) -> String {
    format!("version={version}\n")
}

/// The version [`PROJECTION`] states: its first `version=` line, past the `#` banner.
///
/// Exactly what `bin/majordomus` reads at start-up, so the executable and the shell tool
/// cannot disagree about what the file says.
///
/// ```
/// use majordomus_cli::release::version::parse_projection;
/// let file = "# GENERATED FILE — DO NOT EDIT DIRECTLY\n# Generator: majordomus-cli 0.9.0\nversion=0.9.0\n";
/// assert_eq!(parse_projection(file).as_deref(), Some("0.9.0"));
/// // a file that states nothing states no version, and an empty value is not one
/// assert_eq!(parse_projection("# nothing here\n"), None);
/// assert_eq!(parse_projection("version=\n"), None);
/// ```
pub fn parse_projection(text: &str) -> Option<String> {
    text.lines()
        .filter(|l| !l.trim_start().starts_with('#'))
        .find_map(|l| l.strip_prefix("version="))
        .map(|v| v.trim().to_string())
        .filter(|v| !v.is_empty())
}

/// The version the shell tool prints: what [`PROJECTION`] states.
