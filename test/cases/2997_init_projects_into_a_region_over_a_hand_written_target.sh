# majordomus-covers: init update
# majordomus-negative: update
# claims: no-silent-overwrite, projection-generation
# init projects into a region where a hand-written target already exists.
#
# A repository worth supervising usually has a CLAUDE.md or an AGENTS.md somebody wrote. The
# skeleton's policy projects every provider file whole, so the first `update` after `init`
# met those files and refused, advising --force: the one flag that loses them. Region mode,
# which keeps them, had to be found in a guide and set by hand (adoption finding G05).
#
# init now reads what is there. A projection target that exists and carries no generation
# stamp was not written by `update`, so the policy init creates gives that projection
# `mode: region`, and init names each target it did that for. A target that is absent, or
# that `update` generated whole, keeps the skeleton's declaration, and a repository with
# none of them gets the skeleton's policy byte for byte. A whole-file projection that still
# meets a hand-written file is refused with the way to keep the file named first.
. "$ROOT/test/lib.sh"

# the projection entry of a target in the policy: the lines from its `target:` to the next
# list item, on stdout
entry_of() {
  awk -v t="    target: $1" '
    $0 == t { on = 1; print; next }
    on && /^  - / { exit }
    on && /^[^ ]/ { exit }
    on { print }' .ai/repo/policy.yaml
}
in_region_mode() { entry_of "$1" | grep -qx '    mode: region'; }

# --- a repository with none of the targets gets the skeleton's policy, byte for byte
expect_exit 0 "$MJ" init
expect_no_grep 'mode: region'
cmp -s .ai/repo/policy.yaml "$ROOT/share/skeleton/policy.yaml" \
  || { echo "    a repository with no projection target did not get the skeleton's policy"; exit 1; }

# --- so does one whose targets update generated: a stamped file is the tool's own
expect_exit 0 "$MJ" update
expect_grep '^create CLAUDE.md$'
rm -rf .ai
expect_exit 0 "$MJ" init
expect_no_grep 'mode: region'
cmp -s .ai/repo/policy.yaml "$ROOT/share/skeleton/policy.yaml" \
  || { echo "    generated targets changed the policy init writes"; exit 1; }

# --- the adopter: two hand-written targets, the third absent
rm -rf .ai AGENTS.md CLAUDE.md GEMINI.md
cat > CLAUDE.md <<'MD'
# CLAUDE.md

Hand-written governance that predates Majordomus. Nothing here is generated.

## A rule the repository already had

Keep it.
MD
# no newline at the end: the bytes are kept as they are, not tidied
printf '# AGENTS.md\n\nWritten by a person, with no final newline.' > AGENTS.md
cp CLAUDE.md claude.before; cp AGENTS.md agents.before

expect_exit 0 "$MJ" init
# init says which targets it projects into a region, one line each, and names the policy
expect_grep '^region: AGENTS\.md exists and was not generated by update; \.ai/repo/policy\.yaml projects into it with mode: region'
expect_grep '^region: CLAUDE\.md exists and was not generated by update; \.ai/repo/policy\.yaml projects into it with mode: region'
expect_no_grep '^region: GEMINI\.md'
in_region_mode AGENTS.md || { echo "    AGENTS.md exists hand-written and its projection is not mode: region"; exit 1; }
in_region_mode CLAUDE.md || { echo "    CLAUDE.md exists hand-written and its projection is not mode: region"; exit 1; }
in_region_mode GEMINI.md && { echo "    GEMINI.md is absent and its projection was made a region"; exit 1; }
# nothing else of the policy moved: without the added lines it is the skeleton's
grep -vx '    mode: region' .ai/repo/policy.yaml | cmp -s - "$ROOT/share/skeleton/policy.yaml" \
  || { echo "    init changed more of the policy than the mode of the existing targets"; exit 1; }
[ "$(grep -cx '    mode: region' .ai/repo/policy.yaml)" = 2 ]
# init wrote the policy and not the targets
cmp -s CLAUDE.md claude.before && cmp -s AGENTS.md agents.before \
  || { echo "    init changed a projection target"; exit 1; }

# --- the plan writes nothing and is not refused; update then keeps every byte outside the region
expect_exit 0 "$MJ" update --dry-run
expect_no_grep 'REFUSE'
expect_grep '^create GEMINI.md$'
cmp -s CLAUDE.md claude.before && cmp -s AGENTS.md agents.before \
  || { echo "    update --dry-run wrote a target"; exit 1; }
expect_exit 0 "$MJ" update
expect_no_grep 'REFUSE'
for pair in CLAUDE.md:claude.before AGENTS.md:agents.before; do
  f="${pair%%:*}"; was="${pair#*:}"; n="$(wc -c < "$was" | tr -d ' ')"
  # the document as it was is the head of the file, byte for byte
  head -c "$n" "$f" | cmp -s - "$was" || { echo "    update changed the hand-written part of $f"; exit 1; }
  # and what follows it is one separating newline and the region, to the last line
  tail -c +"$((n + 1))" "$f" > rest.txt
  [ "$(sed -n '1p' rest.txt)" = "" ] || { echo "    $f: the region does not follow the document after one newline"; exit 1; }
  sed -n '2p' rest.txt | grep -qE '^<!-- majordomus:begin [0-9a-f]{12} [0-9a-f]{16} -->$' \
    || { echo "    $f: no region was appended"; exit 1; }
  [ "$(tail -n 1 "$f")" = '<!-- majordomus:end -->' ] || { echo "    $f: text follows the region"; exit 1; }
done
# the absent target is generated whole, as before
expect_grep '^<!-- generated by `majordomus update` from ' GEMINI.md
# deterministic from here on
expect_exit 0 "$MJ" update
expect_grep '^unchanged CLAUDE.md$'
expect_grep '^unchanged AGENTS.md$'

# --- a whole-file projection over a hand-written file is still refused, and the refusal
# names the way to keep the file before the way to replace it
rm -rf .ai AGENTS.md GEMINI.md
cp claude.before CLAUDE.md
expect_exit 0 "$MJ" init
cp "$ROOT/share/skeleton/policy.yaml" .ai/repo/policy.yaml
expect_exit 15 "$MJ" update
expect_grep 'REFUSE projection +CLAUDE.md — carries no generation stamp'
expect_grep 'REFUSE projection +CLAUDE.md — .*to keep it, set `mode: region` for this projection in \.ai/repo/policy\.yaml'
expect_grep 'REFUSE projection +CLAUDE.md — .*to replace it, use --diff CLAUDE.md, then --force'
cmp -s CLAUDE.md claude.before || { echo "    a refused update wrote the target"; exit 1; }
# a region whose own content was edited is another matter: region mode is already set
# there, and that refusal does not offer it
cp claude.before CLAUDE.md
rm -rf .ai; expect_exit 0 "$MJ" init
"$MJ" update >/dev/null
awk '/^<!-- majordomus:begin/{print; getline; print "EDITED " $0; next} {print}' CLAUDE.md > c.tmp && mv c.tmp CLAUDE.md
expect_exit 15 "$MJ" update
expect_grep 'REFUSE projection +CLAUDE.md'
expect_no_grep 'to keep it, set'

# --- --extend overwrites nothing: a policy that exists is the repository's, whatever it says
rm -rf .ai AGENTS.md GEMINI.md
cp claude.before CLAUDE.md
expect_exit 0 "$MJ" init
cp "$ROOT/share/skeleton/policy.yaml" .ai/repo/policy.yaml
expect_exit 0 "$MJ" init --extend
expect_no_grep '^region: '
cmp -s .ai/repo/policy.yaml "$ROOT/share/skeleton/policy.yaml" \
  || { echo "    --extend rewrote a policy that existed"; exit 1; }
# and where --extend is what seeds the policy, it reads the targets as a first init does
rm .ai/repo/policy.yaml
expect_exit 0 "$MJ" init --extend
expect_grep '^region: CLAUDE\.md exists and was not generated by update'
in_region_mode CLAUDE.md || { echo "    --extend seeded a whole-file projection over a hand-written CLAUDE.md"; exit 1; }
in_region_mode AGENTS.md && { echo "    --extend made a region of an absent target"; exit 1; }
exit 0
