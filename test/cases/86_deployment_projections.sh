# majordomus-covers: none
# majordomus-exclusive: edits .dockerignore and deploy/gigalixir/bin/compile in this checkout to prove a hand edit is refused, then restores them
# The deployment artifacts are projections of the deployment object, and only that.
#
# A hand-written Dockerfile, ignore file or Procfile would restate the port and the build
# inputs the repository already knows, and every pair would drift the first time one half
# changed. So they are generated, they say so in their own first lines, and
# `generate --check` refuses a tree where one was edited. The object names Gigalixir
# (ADR 0219), so the provider's Procfile and the inline buildpack's hooks under
# deploy/gigalixir/ are among them; Fly.io stays no target (2026-10-12), so the tree carries
# no fly.toml.
#
# The case runs against this checkout's own deployment object, because that is the object
# whose projections are committed and whose drift would ship.
. "$ROOT/test/lib.sh"
RB="$(rust_bin)" || rust_bin_exit $?
MAJORDOMUS_SHARE="$ROOT/share"; export MAJORDOMUS_SHARE
W="$(mktemp -d "${TMPDIR:-/tmp}/mj86.XXXXXX")"; trap 'rm -rf "$W"' EXIT

# ---------------------------------------------------------------- the committed tree is current
"$RB" generate --repo "$ROOT" --check deployment >"$W/check.log" 2>&1 \
  || { echo "    the committed deployment artifacts are stale:"; tail -3 "$W/check.log"; exit 1; }

# ---------------------------------------------------------------- each says what it is
GX=deploy/gigalixir
for f in deploy/Dockerfile .dockerignore $GX/Procfile $GX/bin/detect $GX/bin/compile $GX/bin/release; do
  [ -f "$ROOT/$f" ] || { echo "    $f was never generated"; exit 1; }
  head -4 "$ROOT/$f" | grep -q 'GENERATED by `majordomus generate deployment`' \
    || { echo "    $f does not say it is generated"; exit 1; }
  head -4 "$ROOT/$f" | grep -q '\.ai/repo/deployments/' \
    || { echo "    $f does not name the object it came from"; exit 1; }
done

# Fly.io is no target: the tree carries no fly.toml, and since `generate --check` above
# passed, the generator does not plan one either (a planned file that is absent is stale).
[ ! -e "$ROOT/fly.toml" ] || { echo "    fly.toml is still in the tree, and Fly.io is no target"; exit 1; }

# ---------------------------------------------------------------- the provider's files
# A hook is a script: the kernel reads its interpreter from line 1, so the banner is on line 2.
for f in $GX/bin/detect $GX/bin/compile $GX/bin/release; do
  [ "$(sed -n 1p "$ROOT/$f")" = '#!/bin/sh' ] || { echo "    $f does not open with its interpreter"; exit 1; }
  sed -n 2p "$ROOT/$f" | grep -q '^# GENERATED FILE' || { echo "    $f does not carry the banner on line 2"; exit 1; }
done
# The Procfile starts the executable the slug carries, serving the layer it carries, on the
# provider's PORT and every interface; the fallback port is the object's own. On the mesh it
# advertises the provider URL the object names and reads its node key from the secret
# MAJORDOMUS_MESH_NODE_SEED (ADR 0220), which the Procfile names and never holds.
web="$(grep '^web: ' "$ROOT/$GX/Procfile")"
[ "$(grep -c '^web: ' "$ROOT/$GX/Procfile")" = 1 ] || { echo "    the Procfile does not declare exactly one web process"; exit 1; }
url="$(sed -n 's/^ *url: *//p' "$ROOT/.ai/repo/deployments/majordomus.yaml" | head -n 1)"
case "$web" in
  "web: ./.majordomus/bin/majordomus serve --repo . --discovery filesystem --host 0.0.0.0 --port \${PORT:-"*"} --idle 0 --advertise $url --node-seed-env MAJORDOMUS_MESH_NODE_SEED") ;;
  *) echo "    the Procfile's web process is not the declared start command: $web"; exit 1 ;;
esac
# every other line is a comment the provider ignores
grep -vE '^(#|web: |$)' "$ROOT/$GX/Procfile" && { echo "    the Procfile carries a line that is neither the process nor a comment"; exit 1; }

# ---------------------------------------------------------------- one fact, one image
# The port is in the object; it must appear in the image definition because it was rendered
# from it, and nowhere as a literal somebody typed.
port="$(sed -n 's/^  port: \([0-9]*\)$/\1/p' "$ROOT/.ai/repo/deployments/majordomus.yaml")"
[ -n "$port" ] || { echo "    the object states no port"; exit 1; }
grep -q "^EXPOSE $port$" "$ROOT/deploy/Dockerfile" || { echo "    the image does not expose the declared port"; exit 1; }
# and the Procfile falls back to it where the provider injects no PORT
case "$web" in
  *" --port \${PORT:-$port} "*) ;;
  *) echo "    the Procfile's port fallback is not listen.port ($port): $web"; exit 1 ;;
esac
# and the health routes the image smoke polls are the ones the object names
for key in liveness readiness; do
  route="$(sed -n "s|^  $key: \(/.*\)$|\1|p" "$ROOT/.ai/repo/deployments/majordomus.yaml")"
  [ -n "$route" ] || { echo "    the object states no $key route"; exit 1; }
  grep -qF "\$url$route\"" "$ROOT/.github/actions/image-smoke/action.yml" \
    || { echo "    the image smoke does not poll $route"; exit 1; }
done

# ---------------------------------------------------------------- the image carries no toolchain
grep -q '^FROM .* AS build$' "$ROOT/deploy/Dockerfile" || { echo "    the image is not multi-stage"; exit 1; }
grep -q '^USER ' "$ROOT/deploy/Dockerfile" || { echo "    the image runs as root"; exit 1; }
# and the one directory it writes is its own: everything copied is root's, and an image whose
# process could not create its lease under .ai/local stopped at start and never served
awk '/^COPY \.ai /{c=1} /^RUN install -d -o majordomus -g majordomus \/app\/\.ai\/local$/{o=c} /^USER /{exit !o}' "$ROOT/deploy/Dockerfile" \
  || { echo "    the unprivileged process cannot write the layer's local half"; exit 1; }
[ "$(grep -c '^COPY --from=binary ' "$ROOT/deploy/Dockerfile")" = 1 ] && ! grep -q '^COPY --from=build ' "$ROOT/deploy/Dockerfile" \
  || { echo "    the runtime stage does not take the binary from the one binary stage"; exit 1; }
# every named stage is a builder stage; the one unnamed FROM is the runtime
awk '/^FROM .* AS [a-z]+$/{b=1} /^FROM [^ ]*$/{b=0} !b && /cargo|rustup|apk add/{print; found=1} END{exit found}' "$ROOT/deploy/Dockerfile" \
  || { echo "    the runtime stage carries a build toolchain"; exit 1; }
# nothing local, nothing secret
grep -qE '/Users/|/home/|_TOKEN|_SECRET|_API_KEY|FlyV1|fo1_' "$ROOT/deploy/Dockerfile" "$ROOT/.dockerignore" \
  "$ROOT/$GX/Procfile" "$ROOT/$GX/bin/detect" "$ROOT/$GX/bin/compile" "$ROOT/$GX/bin/release" \
  && { echo "    a generated artifact carries an absolute developer path or a credential"; exit 1; }

# ---------------------------------------------------------------- the builder is the repository's toolchain
# One pin: rust-toolchain.toml. The image stood on rust:1.85 while the repository built with
# 1.98.1, and 1.85 cannot compile the locked dependencies (tiktoken-rs uses let chains), so
# the committed image definition did not build at all and nothing said so.
toolchain="$(sed -n 's/^channel = "\([0-9.]*\)".*/\1/p' "$ROOT/rust-toolchain.toml")"
[ -n "$toolchain" ] || { echo "    rust-toolchain.toml pins no exact channel"; exit 1; }
grep -q "^FROM rust:${toolchain}-alpine[0-9.]* AS toolchain$" "$ROOT/deploy/Dockerfile" \
  || { echo "    the builder is not the repository's Rust $toolchain: $(grep '^FROM rust:' "$ROOT/deploy/Dockerfile")"; exit 1; }
# builder and runtime link against and run the same musl
b_alpine="$(sed -n 's/^FROM rust:[0-9.]*-alpine\([0-9.]*\) AS toolchain$/\1/p' "$ROOT/deploy/Dockerfile")"
grep -q "^FROM alpine:${b_alpine}$" "$ROOT/deploy/Dockerfile" \
  || { echo "    the runtime's Alpine is not the builder's ($b_alpine)"; exit 1; }

# ---------------------------------------------------------------- the dependencies are compiled where a cache can carry them
# A cache mount never leaves the builder it was made on, so on a fresh runner it saves
# nothing by itself; the compiled dependencies must be a stage's own layer content, and
# nothing that moves with every commit may come before them. The one mount is sccache's,
# beside the layer and never instead of it: the target directory is never mounted.
[ "$(sed -n 's/^FROM .* AS \([a-z]*\)$/\1/p' "$ROOT/deploy/Dockerfile" | tr '\n' ' ')" = 'toolchain recipe deps build release binary ' ] \
  || { echo "    the builder stages are not toolchain, recipe, deps, build, release, binary"; exit 1; }
grep -o -- '--mount=type=cache[^ ]*' "$ROOT/deploy/Dockerfile" | grep -vx -- '--mount=type=cache,id=majordomus-sccache,target=/sccache' \
  && { echo "    a cache mount other than sccache's holds compiler output no registry export carries"; exit 1; }
[ "$(grep -c -- '--mount=type=cache,id=majordomus-sccache,target=/sccache' "$ROOT/deploy/Dockerfile")" = 2 ] \
  || { echo "    the deps and build stages do not both compile behind the sccache mount"; exit 1; }
grep -q '^ENV RUSTC_WRAPPER=sccache ' "$ROOT/deploy/Dockerfile" || { echo "    cargo does not run behind sccache"; exit 1; }
awk '/ AS build$/{exit} /MAJORDOMUS_BUILD_(COMMIT|DIRTY)/{print; found=1} END{exit found}' "$ROOT/deploy/Dockerfile" \
  || { echo "    a stage before build reads the commit, so every commit recompiles the dependencies"; exit 1; }
# The one other input a stage before build may copy is a path crate the package compiles
# against, as the deployment declares it under build.crates (I2784): each is copied whole,
# to its own path, before the dependencies are compiled, and never into the runtime image.
crates="$(awk '/^build:/{b=1; next} b && /^[^ #]/{b=0} b && /^  crates:/{c=1; next}
  c && /^    - /{print $2; next} c{c=0}' "$ROOT/.ai/repo/deployments/majordomus.yaml")"
[ -n "$crates" ] || { echo "    the deployment declares no build.crates"; exit 1; }
awk -v crates="$crates" 'BEGIN{n=split(crates, c, "\n"); for (i=1; i<=n; i++) ok["COPY " c[i] " ./" c[i]]=1}
  / AS build$/{exit} /^COPY / && !/^COPY --from=recipe / && !/Cargo\.toml .*Cargo\.lock / && !($0 in ok){print; found=1}
  END{exit found}' "$ROOT/deploy/Dockerfile" \
  || { echo "    a stage before build copies more than the manifest, the lockfile and the declared crates"; exit 1; }
for crate in $crates; do
  awk -v want="COPY $crate ./$crate" '/ AS build$/{exit} $0 == want{found=1} END{exit !found}' "$ROOT/deploy/Dockerfile" \
    || { echo "    the declared crate $crate is not in the dependency stage"; exit 1; }
  if awk -v crate="$crate" '/^FROM alpine/{rt=1} rt && /^COPY / && index($0, " " crate " "){found=1}
      END{exit !found}' "$ROOT/deploy/Dockerfile"; then
    echo "    the declared crate $crate is copied into the runtime image"; exit 1
  fi
done

# ---------------------------------------------------------------- a release image compiles nothing
# MAJORDOMUS_BINARY_FROM=release takes the release's own published executable from the
# release-binary build context; the default compiles. The argument is declared before the
# first FROM (a FROM can only name a global argument), and the release stage neither
# compiles nor reads the commit: the commit is the one the archive was built from.
awk '/^FROM /{exit} /^ARG MAJORDOMUS_BINARY_FROM=build$/{found=1} END{exit !found}' "$ROOT/deploy/Dockerfile" \
  || { echo "    the binary source is not a global argument defaulting to build"; exit 1; }
grep -qx 'FROM ${MAJORDOMUS_BINARY_FROM} AS binary' "$ROOT/deploy/Dockerfile" || { echo "    no stage chooses the binary"; exit 1; }
awk '/ AS release$/{r=1; next} /^FROM /{r=0} r && /cargo|MAJORDOMUS_BUILD_/{print; found=1} END{exit found}' "$ROOT/deploy/Dockerfile" \
  || { echo "    the release stage compiles or names a commit of its own"; exit 1; }
grep -qx 'COPY --from=release-binary majordomus-${TARGETARCH} /out/majordomus' "$ROOT/deploy/Dockerfile" \
  || { echo "    the release stage does not take the executable from the release-binary context"; exit 1; }

# ---------------------------------------------------------------- the context is bounded
# Everything is excluded and the declared inputs are let back in, so a file that appears in
# the repository tomorrow does not appear in the image tomorrow.
# The first line that is not the generated banner must be `*`. Counting header lines was
# the same second statement of one fact this whole case exists to remove: the banner grew a
# line, `*` moved to the seventh, and a `head -6` window said the context was unbounded.
first="$(grep -vE '^[[:space:]]*(#|$)' "$ROOT/.dockerignore" | head -1)"
[ "$first" = '*' ] || { echo "    the ignore file does not exclude everything first (first rule: '$first')"; exit 1; }
grep -qx '\*\*/.git' "$ROOT/.dockerignore" || { echo "    the image would carry repository history"; exit 1; }
grep -qx '.ai/local' "$ROOT/.dockerignore" || { echo "    the image would carry the checkout-local half of the layer"; exit 1; }
for input in $(sed -n 's/^    - //p' "$ROOT/.ai/repo/deployments/majordomus.yaml"); do
  grep -qx "!$input" "$ROOT/.dockerignore" || { echo "    the build context does not carry the declared input $input"; exit 1; }
done

# ---------------------------------------------------------------- a hand edit is refused
cp "$ROOT/.dockerignore" "$W/dockerignore.keep"
printf '!a-hand-added-input\n' >> "$ROOT/.dockerignore"
"$RB" generate --repo "$ROOT" --check deployment >"$W/edited.log" 2>&1 \
  && { cp "$W/dockerignore.keep" "$ROOT/.dockerignore"; echo "    a hand edit to .dockerignore was accepted"; exit 1; }
grep -q '\.dockerignore (differs)' "$W/edited.log" \
  || { cp "$W/dockerignore.keep" "$ROOT/.dockerignore"; echo "    the refusal did not name .dockerignore"; exit 1; }
cp "$W/dockerignore.keep" "$ROOT/.dockerignore"

# a hook too: a hand edit to a provider file is refused like one to the image definition
cp "$ROOT/$GX/bin/compile" "$W/compile.keep"
printf 'echo a-hand-added-step\n' >> "$ROOT/$GX/bin/compile"
"$RB" generate --repo "$ROOT" --check deployment >"$W/edited-hook.log" 2>&1 \
  && { cp "$W/compile.keep" "$ROOT/$GX/bin/compile"; echo "    a hand edit to $GX/bin/compile was accepted"; exit 1; }
grep -q 'deploy/gigalixir/bin/compile (differs)' "$W/edited-hook.log" \
  || { cp "$W/compile.keep" "$ROOT/$GX/bin/compile"; echo "    the refusal did not name $GX/bin/compile"; exit 1; }
cp "$W/compile.keep" "$ROOT/$GX/bin/compile"

# and regeneration puts it back exactly
"$RB" generate --repo "$ROOT" --check deployment >/dev/null 2>&1 \
  || { echo "    the tree was not restored"; exit 1; }
