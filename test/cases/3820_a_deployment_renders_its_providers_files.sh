# majordomus-covers: none
# A deployment that names its provider renders every file that provider reads (I3820, ADR 0219).
#
# The first Gigalixir deployment was a slug assembled by hand: its start command, its port
# and its file list restated what the deployment object already said, and nothing checked
# them. So the object names the provider, and `majordomus generate deployment` writes the
# provider's files from it under deploy/<provider>/, each with the provenance header, under
# `generate --check` like the image definition. This case renders a fixture object that
# names Gigalixir and proves the four files are there, each says what it is, the Procfile
# starts the declared executable on the provider's PORT falling back to the declared port,
# a hand edit is refused, and an object that names no provider renders no provider file.
. "$ROOT/test/lib.sh"
RB="$(rust_bin)" || rust_bin_exit $?
MAJORDOMUS_SHARE="$ROOT/share"; export MAJORDOMUS_SHARE

"$MJ" init >/dev/null
# the builder stage pins the toolchain the repository builds with, so the fixture states one
printf '[toolchain]\nchannel = "1.98.1"\n' > rust-toolchain.toml

write_deployment() {   # port, provider block (may be empty)
  cat > .ai/repo/deployments/hosted.yaml <<MD
schema: deployment/v1
kind: deployment
id: hosted
title: The hosted deployment
application: hosted
build:
  package: majordomus-cli
  binary: majordomus
  profile: release
  inputs:
    - .ai
listen:
  port: $1
  interface: all
health:
  liveness: /api/v1/live
  readiness: /api/v1/ready
resources:
  cpu_kind: shared
  cpus: 1
  memory_mb: 256
machines:
  count: 1
  min_running: 0
  autostart: true
  autostop: true
region: fra
$2
MD
}

PROVIDER='provider:
  name: gigalixir
  app: hosted-app
  stack: gigalixir-24
  url: https://hosted-app.gigalixirapp.com'

write_deployment 8091 "$PROVIDER"
git add -A >/dev/null; git commit -qm "a deployment that names its provider" >/dev/null

# ---------------------------------------------------------------- the four files are rendered
expect_exit 0 "$RB" generate --repo . deployment
GX=deploy/gigalixir
for f in $GX/Procfile $GX/bin/detect $GX/bin/compile $GX/bin/release; do
  [ -f "$f" ] || { echo "    $f was not rendered"; ls -R deploy 2>/dev/null; exit 1; }
  head -7 "$f" | grep -q 'GENERATED by `majordomus generate deployment` from \.ai/repo/deployments/hosted\.yaml\.' \
    || { echo "    $f does not name the object it came from"; head -7 "$f"; exit 1; }
done
# a hook is a script: its interpreter on line 1, the banner on line 2
for f in $GX/bin/detect $GX/bin/compile $GX/bin/release; do
  [ "$(sed -n 1p "$f")" = '#!/bin/sh' ] || { echo "    $f does not open with #!/bin/sh"; exit 1; }
  sed -n 2p "$f" | grep -q '^# GENERATED FILE' || { echo "    $f does not carry the banner on line 2"; exit 1; }
done
[ "$(tail -1 $GX/bin/detect)" = 'echo majordomus' ] || { echo "    the detect hook does not name the slug"; exit 1; }
grep -qx 'chmod 755 "$1/.majordomus/bin/majordomus"' $GX/bin/compile \
  || { echo "    the compile hook does not make the slug's executable runnable"; exit 1; }
grep -qx '"$1/.majordomus/bin/majordomus" --version' $GX/bin/compile \
  || { echo "    the compile hook does not prove the executable starts"; exit 1; }
[ "$(tail -1 $GX/bin/release)" = 'echo "--- {}"' ] || { echo "    the release hook does not declare an empty release"; exit 1; }

# ---------------------------------------------------------------- the Procfile starts the declared executable
want='web: ./.majordomus/bin/majordomus serve --repo . --discovery filesystem --host 0.0.0.0 --port ${PORT:-8091} --idle 0'
[ "$(grep '^web: ' $GX/Procfile)" = "$want" ] \
  || { echo "    the Procfile is not the declared start command:"; cat $GX/Procfile; exit 1; }
# the fallback port is the object's, read again after the object moves it
write_deployment 8092 "$PROVIDER"
expect_exit 0 "$RB" generate --repo . deployment
grep -qF -- '--port ${PORT:-8092} ' $GX/Procfile || { echo "    the Procfile did not follow listen.port"; cat $GX/Procfile; exit 1; }

# ---------------------------------------------------------------- generate --check holds them
expect_exit 0 "$RB" generate --repo . --check deployment
printf 'web: ./somewhere-else serve\n' >> $GX/Procfile
expect_exit 10 "$RB" generate --repo . --check deployment
expect_grep 'deploy/gigalixir/Procfile \(differs\)'
expect_exit 0 "$RB" generate --repo . deployment
expect_exit 0 "$RB" generate --repo . --check deployment

# ---------------------------------------------------------------- no provider, no provider file
rm -rf deploy
write_deployment 8091 ""
expect_exit 0 "$RB" generate --repo . deployment
[ -f deploy/Dockerfile ] || { echo "    the image definition was not rendered"; exit 1; }
[ ! -e $GX ] || { echo "    an object that names no provider rendered provider files"; ls -R $GX; exit 1; }
