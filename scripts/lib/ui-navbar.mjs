// ui-navbar.mjs: the site's navbar is the product's navbar. majordomus.dev is the reference for
// how the product looks (project.the-ui-wears-the-sites-navbar), so the bar `majordomus ui`
// draws is not a second bar written after the first one: it is the site's own rendering of
// site/templates/partials/navbar.html over site/data/nav.toml, cut out of the built site and
// compiled into the executable (apps/majordomus-cli/src/ui/navbar.html).
//
// Two halves, both run by `scripts/ui navbar`:
//
//   fragment()  what the executable is given: the bar of the built site's not-found page — the
//               one page on which no group is current — with the two things that are this
//               build's rather than the declaration's made into what the executable fills in:
//               the release the badge names becomes the version slot, and a link to the site
//               map at the foot of every site page leads to that map on the site's front page,
//               because a UI page has no such foot. Comments go: they are the build's.
//   compare()   whether the bar a reader meets on /ui is that bar: every element of the site's
//               bar and of the UI's, in document order, with its tag, its classes, its
//               rendered box and the computed styles that make it look the way it does, in
//               both themes, at the widths the design declares, closed and with a menu open.
//
// What may differ is named here and nowhere else: a link's target (the UI leads to the live
// surface where the site leads to its published snapshot, and the note that says "snapshot"
// goes with it), the version the badge names (the site names the release it offers, the UI
// the executable that drew it), and which entry is current.
import { readFileSync } from 'node:fs';

export const VERSION_SLOT = '@MJ_VERSION@';
export const GENERATED = '<!-- generated by `scripts/ui navbar --write` from the built site '
  + '(site/templates/partials/navbar.html over site/data/nav.toml); never edited -->';

/** The language the site is written in (site/i18n/languages.json). */
const SOURCE_LANGUAGE = JSON.parse(readFileSync(new URL('../../site/i18n/languages.json',
  import.meta.url), 'utf8')).source;

/** The `<nav aria-label="Main">` element of a rendered page, as written. */
export function cut(html) {
  const open = html.match(/<nav\b[^>]*\baria-label="Main"[^>]*>/);
  if (!open) return null;
  const end = html.indexOf('</nav>', open.index);
  if (end < 0) return null;
  return html.slice(open.index, end + '</nav>'.length);
}

/** The fragment the executable compiles in, from a page of the site built for `origin`. */
export function fragment(html, origin) {
  const bar = cut(html);
  if (!bar) throw new Error('the page carries no <nav aria-label="Main">');
  if (!bar.includes(`href="${origin}/"`)) {
    throw new Error(`the bar does not lead to ${origin}/: the site was built for another origin `
      + '(a build for the running server?); run: scripts/site-build');
  }
  // a comment is the build's, not the bar's: the mark's names the generator's version, and a
  // release would otherwise stale the copy without a pixel of the bar moving
  const body = bar
    .replace(/<!--[\s\S]*?-->\n?/g, '')
    .replace(/data-release="[^"]*">v[^<]*</g, `data-release="${VERSION_SLOT}">v${VERSION_SLOT}<`)
    .replace(/href="#(site-map-[^"]*)"/g, `href="${origin}/#$1"`)
    // the language switch of the not-found page leads to that page in each language; a UI page
    // has no copy in another language yet, so each language leads to the site's front page in
    // it (ADR 0218)
    .replace(/(<a href=")[^"]*("[^>]*\sdata-i18n-lang="([a-z-]+)")/g,
      (all, a, b, lang) => `${a}${origin}/${lang === SOURCE_LANGUAGE ? '' : `${lang}/`}${b}`);
  return `${GENERATED}\n${body}\n`;
}

/** The fragment of the built site under `pub`, built for `origin`. */
export function fragmentOf(pub, origin) {
  return fragment(readFileSync(`${pub}/404.html`, 'utf8'), origin);
}

// --------------------------------------------------------------------------- the comparison

/** The computed properties that decide how an element of the bar looks. */
export const STYLES = [
  'display', 'position', 'top', 'z-index', 'visibility',
  'font-family', 'font-size', 'font-weight', 'line-height', 'letter-spacing', 'white-space',
  'color', 'background-color', 'opacity',
  'border-top-width', 'border-right-width', 'border-bottom-width', 'border-left-width',
  'border-top-color', 'border-bottom-color', 'border-top-style', 'border-bottom-style',
  'border-top-left-radius', 'border-bottom-right-radius',
  'padding-top', 'padding-right', 'padding-bottom', 'padding-left',
  'margin-top', 'margin-right', 'margin-bottom', 'margin-left',
  'column-gap', 'row-gap', 'justify-content', 'align-items', 'flex-direction', 'flex-wrap',
  'box-shadow', 'fill', 'stroke',
];

/**
 * Runs in the page: every element of the bar with what is compared of it. The badge's text is
 * set to one value first, so that two versions of different lengths do not move what follows.
 */
export function describeInPage(styles) {
  const nav = document.querySelector('nav[aria-label="Main"]');
  if (!nav) return null;
  for (const b of nav.querySelectorAll('[data-release]')) b.textContent = 'v0.0.0';
  const out = [];
  const walk = (el, path) => {
    if (el.hasAttribute('data-nav-snapshot-note')) return;
    const cs = getComputedStyle(el);
    const r = el.getBoundingClientRect();
    const own = [...el.childNodes].filter((n) => n.nodeType === 3).map((n) => n.textContent).join('').trim().replace(/\s+/g, ' ');
    out.push({
      path,
      tag: el.tagName.toLowerCase(),
      cls: el.getAttribute('class') || '',
      id: el.id || '',
      label: el.getAttribute('aria-label') || '',
      text: own,
      hidden: el.hasAttribute('hidden'),
      box: [Math.round(r.x), Math.round(r.y), Math.round(r.width), Math.round(r.height)],
      style: Object.fromEntries(styles.map((p) => [p, cs.getPropertyValue(p)])),
    });
    let i = 0;
    for (const c of el.children) walk(c, `${path}>${c.tagName.toLowerCase()}[${i++}]`);
  };
  walk(nav, 'nav');
  return out;
}

/** The differences between two descriptions of the bar, each a line a reader can act on. */
export function compare(site, ui, { tolerance = 1 } = {}) {
  if (!site) return ['the site page has no <nav aria-label="Main">'];
  if (!ui) return ['the UI page has no <nav aria-label="Main">'];
  const out = [];
  const n = Math.max(site.length, ui.length);
  for (let i = 0; i < n; i++) {
    const s = site[i], u = ui[i];
    if (!s || !u) { out.push(`${(s || u).path}: only the ${s ? 'site' : 'UI'} has this element`); continue; }
    if (s.path !== u.path || s.tag !== u.tag) { out.push(`${s.path}: the UI has ${u.path} here; the structure differs from this element on`); break; }
    for (const k of ['cls', 'id', 'label', 'text', 'hidden']) {
      if (s[k] !== u[k]) out.push(`${s.path}: ${k} is ${JSON.stringify(u[k])} on the UI, ${JSON.stringify(s[k])} on the site`);
    }
    if (s.box.some((v, j) => Math.abs(v - u.box[j]) > tolerance)) {
      out.push(`${s.path}: box ${u.box.join(',')} on the UI, ${s.box.join(',')} on the site (x,y,w,h)`);
    }
    for (const [p, v] of Object.entries(s.style)) {
      if (u.style[p] !== v) out.push(`${s.path}: ${p} is ${u.style[p]} on the UI, ${v} on the site`);
    }
  }
  return out;
}

/**
 * Drives a browser over the site's bar and the UI's, in every state the comparison covers, and
 * returns the findings. `siteContext` makes a browser context that answers the site's origin
 * from the build (scripts/lib/browser.mjs serveSite); `uiUrl` is a page of the running UI.
 */
export async function run(browser, { siteContext, siteUrl, uiUrl, widths, themeKey, themes = ['light', 'dark'] }) {
  const findings = [];
  const states = [
    { name: 'closed', act: async () => {} },
    // a wide bar opens its first menu; a narrow one opens the collapsed menu
    { name: 'open', act: async (page) => {
      const wide = await page.evaluate(() => {
        const b = document.querySelector('nav[aria-label="Main"] [data-collapse-toggle]');
        return !b || b.offsetParent === null;
      });
      const sel = wide ? 'nav[aria-label="Main"] [data-dropdown-toggle]' : 'nav[aria-label="Main"] [data-collapse-toggle]';
      await page.click(sel, { timeout: 5000 });
      await page.waitForTimeout(100);
    } },
  ];
  let compared = 0;
  for (const width of widths) for (const theme of themes) for (const state of states) {
    const read = async (ctx, url) => {
      const page = await ctx.newPage();
      await page.goto(url, { waitUntil: 'load', timeout: 60000 });
      await page.waitForTimeout(150);
      await state.act(page);
      const d = await page.evaluate(describeInPage, STYLES);
      await page.close();
      return d;
    };
    const opts = { viewport: { width, height: 900 }, colorScheme: theme };
    // the reader's stored choice, under the key the design declares (site/data/registry/design.json)
    const init = ([k, t]) => { try { localStorage.setItem(k, t); } catch (e) { /* nothing */ } };
    const sctx = await siteContext(opts);
    await sctx.addInitScript(init, [themeKey, theme]);
    const uctx = await browser.newContext(opts);
    await uctx.addInitScript(init, [themeKey, theme]);
    try {
      const diff = compare(await read(sctx, siteUrl), await read(uctx, uiUrl));
      compared += 1;
      for (const d of diff) findings.push(`@${width} ${theme} ${state.name}: ${d}`);
    } catch (e) {
      findings.push(`@${width} ${theme} ${state.name}: ${e.message}`);
    } finally {
      await sctx.close();
      await uctx.close();
    }
  }
  return { findings, compared };
}
