/// ```
/// use majordomus_cli::release::version::{tool, PROJECTION};
/// let dir = tempfile::tempdir().unwrap();
/// assert_eq!(tool(dir.path()), None, "no projection, no version");
/// std::fs::create_dir_all(dir.path().join("share")).unwrap();
/// std::fs::write(dir.path().join(PROJECTION), "version=0.9.0\n").unwrap();
/// assert_eq!(tool(dir.path()).as_deref(), Some("0.9.0"));
/// ```
pub fn tool(root: &Path) -> Option<String> {
    parse_projection(&std::fs::read_to_string(root.join(PROJECTION)).ok()?)
}

/// How [`PROJECTION`] stands against the authority.
///
/// Three answers that lead to three different actions: nothing to do, run the derivation,
/// or find out who wrote a version nobody authored.
///
/// ```
/// use majordomus_cli::release::version::ProjectionState;
/// let stale = ProjectionState::Stale { projected: Some("0.8.0".into()), declared: "0.9.0".into() };
/// // the state every bump leaves behind is not the state nothing could have produced
/// assert_ne!(stale, ProjectionState::Disagrees { projected: "0.8.0".into(), declared: Some("0.9.0".into()) });
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ProjectionState {
    /// Neither the manifest nor the projection is here: this repository does not carry the
    /// product, so there is nothing to project and nothing to compare.
    NotHere,
    /// The projection states the version the manifest declares.
    Current,
    /// The projection is missing, or states an older version than the manifest: the state
    /// between `release bump` and the derivation that follows it. `generate` fixes it.
    Stale {
        /// What the projection states, when it states anything.
        projected: Option<String>,
        /// What the manifest declares.
        declared: String,
    },
    /// The projection states a version newer than the manifest's, or one that cannot be
    /// compared with it, or there is a projection and no manifest. No derivation writes
    /// that, so somebody did.
    Disagrees {
        /// What the projection states.
        projected: String,
        /// What the manifest declares, when there is one.
        declared: Option<String>,
    },
}

/// How [`PROJECTION`] stands against [`MANIFEST`]: compared as versions, so that a projection
/// behind the manifest — what a bump leaves until the derivation runs — is told apart from
/// one ahead of it or unrelated to it, which no derivation ever writes.
///
/// ```
/// use majordomus_cli::release::version::{projection_state, ProjectionState, MANIFEST, PROJECTION};
/// let dir = tempfile::tempdir().unwrap();
/// let root = dir.path();
/// assert_eq!(projection_state(root), ProjectionState::NotHere);
/// std::fs::create_dir_all(root.join("apps/majordomus-cli")).unwrap();
/// std::fs::create_dir_all(root.join("share")).unwrap();
/// std::fs::write(root.join(MANIFEST), "[package]\nversion = \"0.9.0\"\n").unwrap();
/// // raised and not yet derived: stale, which a derivation fixes
/// std::fs::write(root.join(PROJECTION), "version=0.8.0\n").unwrap();
/// assert!(matches!(projection_state(root), ProjectionState::Stale { .. }));
/// // a version the manifest never declared: nothing derives that
/// std::fs::write(root.join(PROJECTION), "version=1.0.0\n").unwrap();
/// assert!(matches!(projection_state(root), ProjectionState::Disagrees { .. }));
/// std::fs::write(root.join(PROJECTION), "version=0.9.0\n").unwrap();
/// assert_eq!(projection_state(root), ProjectionState::Current);
/// ```
pub fn projection_state(root: &Path) -> ProjectionState {
    match (declared(root), tool(root)) {
        (None, None) => ProjectionState::NotHere,
        (None, Some(projected)) => ProjectionState::Disagrees {
            projected,
            declared: None,
        },
        (Some(declared), None) => ProjectionState::Stale {
            projected: None,
            declared,
        },
        (Some(declared), Some(projected)) if declared == projected => ProjectionState::Current,
        (Some(declared), Some(projected)) => {
            match (Version::parse(&projected), Version::parse(&declared)) {
                (Some(p), Some(d)) if p < d => ProjectionState::Stale {
                    projected: Some(projected),
                    declared,
                },
                _ => ProjectionState::Disagrees {
                    projected,
                    declared: Some(declared),
                },
            }
        }
    }
}

/// Whether [`PROJECTION`] states what [`MANIFEST`] declares — the one comparison every
/// surface reports as `agree`.
///
/// ```
/// use majordomus_cli::release::version::projection_current;
/// let dir = tempfile::tempdir().unwrap();
/// // a repository that carries neither has nothing out of step
/// assert!(projection_current(dir.path()));
/// ```
pub fn projection_current(root: &Path) -> bool {
    matches!(
        projection_state(root),
        ProjectionState::Current | ProjectionState::NotHere
    )
}

/// One version written down by hand where the tool's own files live.
///
/// Where it is, to the line, and the shape it was written in — enough for the diagnostic to
/// name the edit that removes it.
///
/// ```
/// use majordomus_cli::release::version::{carrier_shape, Carrier};
/// let line = "FOO_VERSION=\"1.2.3\"";
/// let found = Carrier { path: "lib/x.sh".into(), line: 2, shape: carrier_shape(line).unwrap(), text: line.into() };
/// assert_eq!(found.shape, "an assignment to a version name");
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Carrier {
    /// Repository-relative path.
    pub path: String,
    /// One-based line number.
    pub line: usize,
    /// The shape the version was written in.
    pub shape: &'static str,
    /// The line, trimmed.
    pub text: String,
}

/// The shape a line states a version in, when it states one.
///
/// Three shapes, each a place a version is *declared* rather than mentioned:
///
/// - an assignment to a name ending in `version`, in any case and in the languages the
///   tool's files are written in: shell `MJ_VERSION="0.8.0"` and `export FOO_VERSION=1.2.3`,
///   TOML `version = "1.2.3"`, JavaScript `const VERSION = '1.2.3'`, Python
///   `__version__ = "1.2.3"`;
/// - a `version` member of YAML or JSON at the start of a line: `version: 1.2.3`,
///   `"version": "1.2.3"`;
/// - the product's own answer to `version`: `majordomus 0.8.0`.
///
/// A version is three numbers, optionally after a `v`; a schema's `version: 1` is not one.
///
/// ```
/// use majordomus_cli::release::version::carrier_shape;
/// assert!(carrier_shape("MJ_VERSION=\"0.8.0\"").is_some());
/// assert!(carrier_shape("  export FOO_VERSION=v1.2.3").is_some());
/// assert!(carrier_shape("declare -r MJ_VERSION=\"1.2.3\"").is_some());
/// assert!(carrier_shape("version = \"1.2.3\"").is_some());
/// assert!(carrier_shape("export const VERSION = '1.2.3';").is_some());
/// assert!(carrier_shape("let appVersion = `1.2.3`;").is_some());
/// assert!(carrier_shape("__version__ = \"1.2.3\"").is_some());
/// assert!(carrier_shape("version: 1.2.3").is_some());
/// assert!(carrier_shape("  \"version\": \"1.2.3\",").is_some());
/// assert!(carrier_shape("echo \"majordomus 0.8.0\"").is_some());
/// // read, not stated: a variable, a schema version, a generator stamp, a sentinel, a
/// // comparison, a property of something else
/// assert!(carrier_shape("MJ_VERSION=\"${line#version=}\"").is_none());
/// assert!(carrier_shape("version: 1").is_none());
/// assert!(carrier_shape("# Generator: majordomus-cli 0.8.0").is_none());
/// assert!(carrier_shape("MJ_VERSION=\"site\"").is_none());
/// assert!(carrier_shape("version == \"1.2.3\"").is_none());
/// assert!(carrier_shape("pkg.version = \"1.2.3\"").is_none());
/// assert!(carrier_shape("versioned = \"1.2.3\"").is_none());
/// ```
pub fn carrier_shape(line: &str) -> Option<&'static str> {
    let t = line.trim_start();

    // an assignment to a name ending in `version`, once the words that declare it are set aside
    if let Some((name, value)) = declared_name(t).split_once('=') {
        let name = name.trim_end();
        let is_version_name = !name.is_empty()
            && name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
            && name
                .trim_matches('_')
                .to_ascii_lowercase()
                .ends_with("version");
        let value = value.trim_start().trim_start_matches(['"', '\'', '`']);
        if is_version_name && leads_with_version(value) {
            return Some("an assignment to a version name");
        }
    }

    // a `version` member of YAML or JSON, at the start of a line or of a list item
    let member = t.strip_prefix("- ").unwrap_or(t);
    let after_key = member
        .strip_prefix("\"version\"")
        .or_else(|| member.strip_prefix("'version'"))
        .or_else(|| member.strip_prefix("version"));
    if let Some(rest) = after_key {
        if let Some(value) = rest.trim_start().strip_prefix(':') {
            if leads_with_version(value.trim_start().trim_start_matches(['"', '\''])) {
                return Some("a version member");
            }
        }
    }

    // the product's own answer to `majordomus version`
    const PRODUCT: &str = "majordomus ";
    for (at, _) in t.match_indices(PRODUCT) {
        let before = t[..at].chars().next_back();
        let joined = before.is_some_and(|c| c.is_ascii_alphanumeric() || "-_./".contains(c));
        if !joined && leads_with_version(&t[at + PRODUCT.len()..]) {
            return Some("the product's version line");
        }
    }
    None
}

/// A line with the words that declare a name set aside — `export`, `readonly`, `local`,
/// `declare` and `typeset` with their flags, `const`, `let`, `var` — so that what is left
/// begins with the name being assigned.
fn declared_name(mut t: &str) -> &str {
    const DECLARING: &[&str] = &[
        "export", "readonly", "local", "declare", "typeset", "const", "let", "var",
    ];
    const TAKES_FLAGS: &[&str] = &["export", "readonly", "local", "declare", "typeset"];
    while let Some((word, rest)) = t.split_once(char::is_whitespace) {
        if !DECLARING.contains(&word) {
            break;
        }
        t = rest.trim_start();
        if TAKES_FLAGS.contains(&word) {
            while let Some((flag, rest)) = t.split_once(char::is_whitespace) {
                if flag.len() > 1 && flag.starts_with('-') && !flag.contains('=') {
                    t = rest.trim_start();
                } else {
                    break;
                }
            }
        }
    }
    t
}

/// Whether `text` begins with a version: three dot-separated numbers, optionally after a
/// `v`, and not followed by a fourth.
fn leads_with_version(text: &str) -> bool {
    let bytes = text.strip_prefix('v').unwrap_or(text).as_bytes();
    let mut at = 0;
    for group in 0..3 {
        let start = at;
        while at < bytes.len() && bytes[at].is_ascii_digit() {
            at += 1;
        }
        if at == start {
            return false;
        }
        if group < 2 {
            if bytes.get(at) != Some(&b'.') {
                return false;
            }
            at += 1;
        }
    }
    !matches!(bytes.get(at), Some(b) if *b == b'.' || b.is_ascii_digit())
}

/// Every version written down by hand under [`CARRIER_ROOTS`].
///
/// The files git would commit there — tracked, or new and not ignored, so a file is refused
/// before it is staged rather than after — or, where this is not a git checkout, every file
/// under those directories, so that a tree nobody committed is still read rather than
/// passed. [`PROJECTION`] is not a statement by hand, and neither is any path the generated
/// artifact manifest names: `majordomus generate` wrote those, and `generate --check` is
/// what holds them.
///
/// ```
/// use majordomus_cli::release::version::carriers;
/// let dir = tempfile::tempdir().unwrap();
/// std::fs::create_dir_all(dir.path().join("lib")).unwrap();
/// std::fs::write(dir.path().join("lib/x.sh"), "FOO_VERSION=\"1.2.3\"\n").unwrap();
/// let found = carriers(dir.path());
/// assert_eq!(found.len(), 1);
/// assert_eq!((found[0].path.as_str(), found[0].line), ("lib/x.sh", 1));
/// ```
pub fn carriers(root: &Path) -> Vec<Carrier> {
    let files = committable(root).unwrap_or_else(|| walk(root, CARRIER_ROOTS));
    let generated = generated_paths(root);
    let mut out = Vec::new();
    for path in files {
        if path == PROJECTION || generated.contains(&path) {
            continue;
        }
        let full = root.join(&path);
        let small =
            std::fs::symlink_metadata(&full).is_ok_and(|m| m.is_file() && m.len() <= LARGEST_READ);
        if !small {
            continue;
        }
        let Ok(text) = std::fs::read_to_string(&full) else {
            continue;
        };
        for (i, line) in text.lines().enumerate() {
            if let Some(shape) = carrier_shape(line) {
                out.push(Carrier {
                    path: path.clone(),
                    line: i + 1,
                    shape,
                    text: line.trim().to_string(),
                });
            }
        }
    }
    out
}

/// The files under [`CARRIER_ROOTS`] git would commit: tracked, or untracked and not
/// ignored. `None` when git cannot answer, which is not the same as "no files".
fn committable(root: &Path) -> Option<Vec<String>> {
    let out = crate::git::read_only(root)
        .args([
            "ls-files",
            "-z",
            "--cached",
            "--others",
            "--exclude-standard",
            "--",
        ])
        .args(CARRIER_ROOTS)
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let mut files: Vec<String> = out
        .stdout
        .split(|b| *b == 0)
        .filter(|s| !s.is_empty())
        .map(|s| String::from_utf8_lossy(s).into_owned())
        .collect();
    crate::order::canonical_strings(&mut files);
    files.dedup();
    Some(files)
}

/// Every file under `roots` — directories walked, files taken as they are —
/// repository-relative, in a stable order: the answer when git cannot list them.
fn walk(root: &Path, roots: &[&str]) -> Vec<String> {
    fn visit(dir: &Path, root: &Path, out: &mut Vec<String>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            match entry.file_type() {
                Ok(t) if t.is_dir() => visit(&path, root, out),
                Ok(t) if t.is_file() => {
                    if let Ok(rel) = path.strip_prefix(root) {
                        out.push(rel.to_string_lossy().replace('\\', "/"));
                    }
                }
                _ => {}
            }
        }
    }
    let mut out = Vec::new();
    for dir in roots {
        let full = root.join(dir);
        if full.is_file() {
            out.push((*dir).to_string());
        } else {
            visit(&full, root, &mut out);
        }
    }
    crate::order::canonical_strings(&mut out);
    out
}

/// The paths the committed generated-artifact manifest names.
fn generated_paths(root: &Path) -> BTreeSet<String> {
    std::fs::read_to_string(root.join(GENERATED_MANIFEST))
        .ok()
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
        .and_then(|v| v.get("artifacts").and_then(|a| a.as_array()).cloned())
        .unwrap_or_default()
        .iter()
        .filter_map(|a| a.get("path").and_then(|p| p.as_str()).map(str::to_string))
        .collect()
}

/// Every version label on a line: `v`, a major and a minor, and no patch — `v0.1`, `v1.2`.
///
/// A release is always three numbers (`v0.3.1`), so a label of two names no release: it
/// names the version a text was written about, and it stays where it was typed while the
/// version moves on. A label joined to a word, a path or a URL is not one, and neither is a
/// three-part version or a schema's `version: 1`.
///
/// ```
/// use majordomus_cli::release::version::version_labels;
/// assert_eq!(version_labels("What v0.1 does not do"), ["v0.1"]);
/// assert_eq!(version_labels("(v1.12), and v2.0."), ["v1.12", "v2.0"]);
/// assert!(version_labels("Release `v0.3.1` was published").is_empty());
/// assert!(version_labels("see /releases/v0.1.json and api-v0.1").is_empty());
/// assert!(version_labels("rule v2, schema version: 1, dev0.1").is_empty());
/// assert!(version_labels("v0.1.0 and v0.1x").is_empty());
/// ```
pub fn version_labels(line: &str) -> Vec<String> {
    let bytes = line.as_bytes();
    let joined = |b: u8| b.is_ascii_alphanumeric() || b"./_-".contains(&b);
    let digits = |mut at: usize| {
        while at < bytes.len() && bytes[at].is_ascii_digit() {
            at += 1;
        }
        at
    };
    let mut out = Vec::new();
    for (at, _) in line.match_indices('v') {
        if at > 0 && joined(bytes[at - 1]) {
            continue;
        }
        let major = digits(at + 1);
        if major == at + 1 || bytes.get(major) != Some(&b'.') {
            continue;
        }
        let minor = digits(major + 1);
        if minor == major + 1 {
            continue;
        }
        let patch =
            bytes.get(minor) == Some(&b'.') && bytes.get(minor + 1).is_some_and(u8::is_ascii_digit);
        let glued = bytes
            .get(minor)
            .is_some_and(|b| b.is_ascii_alphanumeric() || b"_-".contains(b));
        if !patch && !glued {
            out.push(line[at..minor].to_string());
        }
    }
    out
}

/// The tracked hand-written prose: documents, the site's authored pages and data, its
/// templates, the layer's own documents and the provider templates.
///
/// Generated files are not prose anybody wrote — a label in one comes from its source, and
/// the source is where it is found — so a path the generated-artifact manifest names, a
/// file stamped by its generator, and a page under `site/content/` that the site generator
/// projects from `site/content-src/` or writes into a subdirectory are all left out. The
/// layer's dated records ([`PROSE_RECORDS`]) are left out too. Where git cannot list the
/// tree — not a checkout — every file under the roots is read instead, as [`carriers`]
/// does, so a tree nobody committed is still read rather than passed.
fn prose_files(root: &Path) -> Vec<String> {
    let listed =
        crate::git::ls_files_any(root, PROSE_ROOTS).unwrap_or_else(|_| walk(root, PROSE_ROOTS));
    let generated = generated_paths(root);
    let prose = |p: &str| match p {
        "README.md" | "AGENTS.md" | "CLAUDE.md" => true,
        _ if PROSE_RECORDS.iter().any(|r| p.starts_with(r)) => false,
        _ if p.starts_with("site/content/") => {
            let name = &p["site/content/".len()..];
            p.ends_with(".md")
                && !name.contains('/')
                && !root.join("site/content-src").join(name).exists()
        }
        _ if p.starts_with("site/data/") => {
            p.ends_with(".toml") && !p["site/data/".len()..].contains('/')
        }
        _ if p.starts_with("share/providers/") || p.starts_with(".ai/repo/providers/") => {
            p.ends_with(".tmpl")
        }
        _ if p.starts_with("site/templates/") => true,
        _ => p.ends_with(".md"),
    };
    listed
        .into_iter()
        .filter(|p| prose(p) && !generated.contains(p))
        .collect()
}

/// A file's text when it is hand-written and small enough to be prose; `None` for one that
/// is missing, binary, oversized or stamped by its generator on its first line.
fn authored_text(root: &Path, path: &str) -> Option<String> {
    const STAMPS: &[&str] = &[
        "<!-- generated by",
        "<!-- GENERATED FILE",
        "# GENERATED FILE",
        "// GENERATED FILE",
    ];
    let full = root.join(path);
    let small =
        std::fs::symlink_metadata(&full).is_ok_and(|m| m.is_file() && m.len() <= LARGEST_READ);
    let text = std::fs::read_to_string(&full).ok().filter(|_| small)?;
    let first = text
        .lines()
        .next()
        .unwrap_or("")
        .trim_start_matches('\u{feff}');
    (!STAMPS.iter().any(|s| first.trim_start().starts_with(s))).then_some(text)
}

/// The entries of [`LABEL_HISTORY`] as `(line, path, reason)`; an absent file declares none.
fn label_history(root: &Path) -> Vec<(usize, String, String)> {
    let text = std::fs::read_to_string(root.join(LABEL_HISTORY)).unwrap_or_default();
    text.lines()
        .enumerate()
        .filter(|(_, l)| !l.trim().is_empty() && !l.trim_start().starts_with('#'))
        .map(|(i, l)| {
            let l = l.trim();
            let (path, reason) = l.split_once(char::is_whitespace).unwrap_or((l, ""));
            (i + 1, path.to_string(), reason.trim().to_string())
        })
        .collect()
}

/// Every version label typed into hand-written prose outside a declared history, and every
/// history entry that cannot be honoured.
///
/// The label is the finding, not the version: `v0.1` on a page that describes the tool as
/// it stands was true the day it was typed and is wrong the day after the next release,
/// while nothing that derives the version can reach it. A document that is *about* a past
/// version names it in [`LABEL_HISTORY`] with a reason. That list is held from both sides:
/// an entry with no reason, one naming a path that is not tracked prose, and one whose
/// document no longer carries a label are each refused, so the list cannot outlive what it
/// exempts.
///
/// ```
/// use majordomus_cli::release::version::{label_diagnostics, LABEL_HISTORY};
/// use std::process::Command;
/// let dir = tempfile::tempdir().unwrap();
/// let root = dir.path();
/// std::fs::create_dir_all(root.join("docs")).unwrap();
/// std::fs::create_dir_all(root.join(".ai/repo")).unwrap();
/// std::fs::write(root.join("README.md"), "What v0.1 does not do.\nRelease v0.3.1 shipped.\n").unwrap();
/// std::fs::write(root.join("docs/DESIGN.md"), "The v0.1 specification.\n").unwrap();
/// std::fs::write(root.join(LABEL_HISTORY), "docs/DESIGN.md the design phase, dated\n").unwrap();
/// let git = |a: &[&str]| {
///     Command::new("git")
///         .env_remove("GIT_DIR").env_remove("GIT_WORK_TREE").env_remove("GIT_INDEX_FILE")
///         .arg("-C").arg(root).args(a).output().unwrap()
/// };
/// git(&["init", "-q"]);
/// git(&["add", "-A"]);
/// let found = label_diagnostics(root);
/// assert_eq!(found.len(), 1, "{found:?}");
/// assert!(found[0].message.starts_with("README.md:1 "), "{}", found[0].message);
///
/// std::fs::write(root.join("docs/DESIGN.md"), "The founding specification.\n").unwrap();
/// let found = label_diagnostics(root);
/// assert_eq!(found[1].id, "version-label-history-invalid", "an exemption outliving its label");
/// ```
pub fn label_diagnostics(root: &Path) -> Vec<Diagnostic> {
    let error = |id: &str, message: String| Diagnostic {
        id: id.into(),
        severity: Severity::Error,
        message,
    };
    let files = prose_files(root);
    let history = label_history(root);
    let exempt: BTreeSet<&str> = history
        .iter()
        .filter(|(_, _, reason)| !reason.is_empty())
        .map(|(_, path, _)| path.as_str())
        .collect();
    let mut out = Vec::new();
    let mut labelled = BTreeSet::new();
    for path in &files {
        let Some(text) = authored_text(root, path) else {
            continue;
        };
        for (i, line) in text.lines().enumerate() {
            let labels = version_labels(line);
            if labels.is_empty() {
                continue;
            }
            labelled.insert(path.as_str());
            if exempt.contains(path.as_str()) {
                continue;
            }
            for label in labels {
                out.push(error(
                    LABEL_IN_PROSE,
                    format!(
                        "{path}:{} names the version it describes as `{label}`: the label \
                         stays while the version moves. Say what is true of the tool as it \
                         stands, without a version; a document about a past version is \
                         declared in {LABEL_HISTORY} with its reason",
                        i + 1
                    ),
                ));
            }
        }
    }
    for (line, path, reason) in &history {
        let at = format!("{LABEL_HISTORY}:{line}");
        if reason.is_empty() {
            out.push(error(
                LABEL_HISTORY_INVALID,
                format!("{at} exempts {path} and says nothing about why: an exemption states its reason"),
            ));
        } else if !files.iter().any(|f| f == path) {
            out.push(error(
                LABEL_HISTORY_INVALID,
                format!("{at} exempts {path}, which is not tracked hand-written prose: remove the entry"),
            ));
        } else if !labelled.contains(path.as_str()) {
            out.push(error(
                LABEL_HISTORY_INVALID,
                format!(
                    "{at} exempts {path}, which names no version label any more: remove the entry"
                ),
            ));
        }
    }
    out
}

/// Everything wrong with where the version is stated: the projection against the
/// authority, and every version written down by hand where the tool's own files live.
///
/// A stale projection is a [`Severity::Warning`] — it is the state every bump leaves until
/// `scripts/derive` runs, `generate --check` is what refuses it, and a writer that refused
/// its own un-derived state could not correct a bump it had just made. A projection nothing
/// could have derived, and a version written by hand, are [`Severity::Error`]s. Asked only
/// where the product lives: a repository without the crate has its own `scripts/` and its
/// own versions, and they are none of this module's business.
///
/// ```
/// use majordomus_cli::release::compat::Severity;
/// use majordomus_cli::release::version::{diagnose, MANIFEST, PROJECTION};
/// let dir = tempfile::tempdir().unwrap();
/// let root = dir.path();
/// std::fs::create_dir_all(root.join("apps/majordomus-cli")).unwrap();
/// std::fs::create_dir_all(root.join("share")).unwrap();
/// std::fs::create_dir_all(root.join("lib")).unwrap();
/// std::fs::write(root.join(MANIFEST), "[package]\nversion = \"0.9.0\"\n").unwrap();
/// std::fs::write(root.join(PROJECTION), "version=0.9.0\n").unwrap();
/// assert!(diagnose(root).is_empty(), "authored once, projected once");
///
/// std::fs::write(root.join("lib/x.sh"), "FOO_VERSION=\"1.2.3\"\n").unwrap();
/// let found = diagnose(root);
/// assert_eq!(found.len(), 1);
/// assert_eq!(found[0].id, "version-stated-by-hand");
/// assert_eq!(found[0].severity, Severity::Error);
/// ```
pub fn diagnose(root: &Path) -> Vec<Diagnostic> {
    let mut out = Vec::new();
    match projection_state(root) {
        ProjectionState::NotHere | ProjectionState::Current => {}
        ProjectionState::Stale {
            projected,
            declared,
        } => out.push(Diagnostic {
            id: PROJECTION_STALE.into(),
            severity: Severity::Warning,
            message: format!(
                "{PROJECTION} states '{}' and {MANIFEST} declares '{declared}': the projection \
                 is stale — run scripts/derive, which builds and then generates it; never edit \
                 it or bin/majordomus",
                projected.as_deref().unwrap_or("nothing")
            ),
        }),
        ProjectionState::Disagrees {
            projected,
            declared,
        } => out.push(Diagnostic {
            id: WRITERS_DISAGREE.into(),
            severity: Severity::Error,
            message: format!(
                "{PROJECTION} states '{projected}' and {MANIFEST} declares '{}': no derivation \
                 writes a version the manifest does not declare, so it was written by hand — \
                 run scripts/derive, and raise the version only with `majordomus release bump`",
                declared.as_deref().unwrap_or("nothing")
            ),
        }),
    }
    if root.join(MANIFEST).is_file() {
        for c in carriers(root) {
            out.push(Diagnostic {
                id: STATED_BY_HAND.into(),
                severity: Severity::Error,
                message: format!(
                    "{}:{} states a version by hand, as {}: `{}`. The version is authored \
                     only in {MANIFEST}; read it with `scripts/release-version` in shell, \
                     `release::version::declared` in Rust, or `bin/majordomus version`",
                    c.path, c.line, c.shape, c.text
                ),
            });
        }
        out.extend(label_diagnostics(root));
    }
    out
}

/// Write `to` into the one place the version is authored, keep the lock's record of it in
/// step, and say which files changed.
///
/// Byte-exact and narrow: the manifest's `version` line inside `[package]`, and the `version`
/// line of the lock's own `majordomus-cli` entry — the one line cargo would rewrite. Nothing
/// else in either file is read or rewritten, so a dependency at the same version is
/// untouched. [`PROJECTION`], the generator stamps and the changelog are not written here:
/// they are derived, and `scripts/derive` derives them.
///
/// ```
/// use majordomus_cli::release::version::{declared, write, MANIFEST};
/// let dir = tempfile::tempdir().unwrap();
/// std::fs::create_dir_all(dir.path().join("apps/majordomus-cli")).unwrap();
/// std::fs::write(dir.path().join(MANIFEST), "[package]\nversion = \"0.8.0\"\n").unwrap();
/// assert_eq!(write(dir.path(), "0.9.0").unwrap(), vec![MANIFEST.to_string()]);
/// assert_eq!(declared(dir.path()).as_deref(), Some("0.9.0"));
/// ```
pub fn write(root: &Path, to: &str) -> std::io::Result<Vec<String>> {
    let mut written = Vec::new();

    let manifest = root.join(MANIFEST);
    let text = std::fs::read_to_string(&manifest)?;
    let mut out = String::with_capacity(text.len());
    let mut in_package = false;
    let mut done = false;
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            in_package = trimmed == "[package]";
        }
        if in_package && !done && trimmed.starts_with("version") && trimmed.contains('"') {
            out.push_str(&format!("version = \"{to}\"\n"));
            done = true;
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
    if out != text {
        std::fs::write(&manifest, out)?;
        written.push(MANIFEST.to_string());
    }

    // The lock's own entry, and only it: the `version` line that follows
    // `name = "majordomus-cli"`. Every other `version` in the file belongs to a dependency.
    let lock = root.join(LOCK);
    if let Ok(text) = std::fs::read_to_string(&lock) {
        let mut out = String::with_capacity(text.len());
        let mut here = false;
        let mut done = false;
        for line in text.lines() {
            let trimmed = line.trim();
            if trimmed == "[[package]]" {
                here = false;
            } else if trimmed == "name = \"majordomus-cli\"" {
                here = true;
            } else if here && !done && trimmed.starts_with("version") && trimmed.contains('"') {
                out.push_str(&format!("version = \"{to}\"\n"));
                here = false;
                done = true;
                continue;
            }
            out.push_str(line);
            out.push('\n');
        }
        if out != text {
            std::fs::write(&lock, out)?;
            written.push(LOCK.to_string());
        }
    }

    Ok(written)
}

/// The version the commit subjects imply: the last release raised by their bump — from the
/// declared version only when nothing was released. Evidence, never the answer on its own.
///
/// It raises the last release and not the declared version, because a declared version
/// already raised for the window must not be raised again by the same commits.
///
/// ```
/// use majordomus_cli::release::version::{commits_imply, Bump};
/// // released 0.10.0, already declared 0.11.0, only features since: 0.11.0, not 0.12.0
/// assert_eq!(commits_imply(Some("0.10.0"), "0.11.0", Bump::Minor).as_deref(), Some("0.11.0"));
/// // nothing released: the declared version is the only base there is
/// assert_eq!(commits_imply(None, "0.3.0", Bump::Patch).as_deref(), Some("0.3.1"));
/// ```
pub fn commits_imply(last: Option<&str>, declared: &str, bump: Bump) -> Option<String> {
    last.and_then(Version::parse)
        .or_else(|| Version::parse(declared))
        .map(|v| v.raised(bump).to_string())
}

/// Who answers `next`, and with what: the contract when it could be measured, and no one
/// when it could not.
///
/// `contract` is the analysis' measured version ([`crate::release::compat::VersionPlan::
/// measured_version`]), or why none could be measured. ADR 0051 refuses an unmeasurable
/// baseline rather than guessing one, so an `Err` leaves `next` absent, [`DecidedBy::
/// Undecided`] and the reason carried — the commit inference stays evidence beside it and
/// never stands in for the measurement. The contract's answer is a minimum: when it is no
/// greater than `last` — only behaviour behind the public boundary changed, so the contract
/// requires no release — it is the release already made, never the next one. Then the
/// commits decide whether anything is released at all, and the contract decides how much:
/// the smallest release above the last, a patch, labelled [`DecidedBy::ContractAndCommits`].
/// The commits never raise `next` beyond what the contract requires.
///
/// ```
/// use majordomus_cli::release::model::DecidedBy;
/// use majordomus_cli::release::version::{decide, Bump};
/// // the commits say BREAKING, the contract only grew: below 1.0 that owes a minor
/// let (next, by, why) = decide(Some("0.10.0"), Bump::Major, Ok("0.11.0".into()));
/// assert_eq!((next.as_deref(), by, why), (Some("0.11.0"), DecidedBy::Contract, None));
/// // only fixes, the surface unchanged: the contract's minimum is the release already made
/// let (next, by, _) = decide(Some("0.10.0"), Bump::Patch, Ok("0.10.0".into()));
/// assert_eq!((next.as_deref(), by), (Some("0.10.1"), DecidedBy::ContractAndCommits));
/// // no published baseline: no one decides, and the reason is carried
/// let (next, by, why) = decide(None, Bump::Minor, Err("no release".into()));
/// assert_eq!((next, by), (None, DecidedBy::Undecided));
/// assert_eq!(why.as_deref(), Some("no release"));
/// ```
pub fn decide(
    last: Option<&str>,
    bump: Bump,
    contract: Result<String, String>,
) -> (Option<String>, DecidedBy, Option<String>) {
    let required = match contract {
        Ok(required) => required,
        Err(why) => return (None, DecidedBy::Undecided, Some(why)),
    };
    match (Version::parse(&required), last.and_then(Version::parse)) {
        (Some(r), Some(l)) if r <= l => match bump {
            Bump::None => (None, DecidedBy::Contract, None),
            _ => (
                Some(l.raised(Bump::Patch).to_string()),
                DecidedBy::ContractAndCommits,
                None,
            ),
        },
        _ => (Some(required), DecidedBy::Contract, None),
    }
}

/// The whole version answer: what is declared, whether the projection the shell tool reads
/// states it, what the public contract requires next, and what the commits since the last
/// release imply — as evidence.
///
/// `contract` is the analysis' answer ([`decide`] says how it is used); [`select`] is the
/// caller that asks it, and the one every surface goes through. The last release is
/// [`crate::release::compat::last_release`] — the same baseline `release analyze` measures
/// from, the highest version the layer records — so the contract and the commit evidence
/// always measure one window. The commit inference raises that release ([`commits_imply`]).
pub fn report(root: &Path, objects: &[Object], contract: Result<String, String>) -> VersionReport {
    let declared = declared(root).unwrap_or_else(|| "unknown".into());
    let tool_version = tool(root).unwrap_or_else(|| "unknown".into());

    let last = super::compat::last_release(root, objects);
    let changes = match &last {
        Some(l) => super::commits::in_range(root, &format!("{}..HEAD", l.read_at), objects),
        None => super::commits::in_range(root, "HEAD", objects),
    };
    let bump = bump_of(&changes);
    let last_version = last.map(|l| l.version);
    let commits_imply = commits_imply(last_version.as_deref(), &declared, bump);
    let (next, decided_by, contract_unreadable) = decide(last_version.as_deref(), bump, contract);

    VersionReport {
        agree: projection_current(root),
        declared,
        tool: tool_version,
        last_release: last_version,
        bump: bump.as_str().to_string(),
        commits_imply,
        next,
        decided_by,
        contract_unreadable,
        changes,
    }
}

/// The release selection: the contract's analysis against the last release, and the version
/// report decided from it — made once, by one function.
///
/// `release version` (the capability, and every surface that renders it) and `release bump`
/// without an explicit target both take their answer from here, so the report and the writer
/// cannot disagree about what the next version is: the report's `next` is the version the
/// writer raises to ([`default_target`]).
///
/// ```
/// use majordomus_cli::capability::registry::CapabilityRegistry;
/// use majordomus_cli::release::model::DecidedBy;
/// use majordomus_cli::release::version::{select, Selection};
/// let dir = tempfile::tempdir().unwrap();
/// let registry = CapabilityRegistry::builder().build().unwrap();
/// let selection: Selection = select(dir.path(), &registry, &[]);
/// // nothing published: no plan, and so a report that decides nothing — with the same reason
/// let why = selection.plan.as_ref().unwrap_err();
/// assert_eq!(selection.report.decided_by, DecidedBy::Undecided);
/// assert_eq!(selection.report.contract_unreadable.as_ref(), Some(why));
/// assert_eq!(selection.report.next, None);
/// ```
#[derive(Debug)]
pub struct Selection {
    /// The analysis `release analyze` makes against the last release, or why it could not be
    /// made at all (no release to compare with, a baseline whose registry is not committed).
    pub plan: Result<super::compat::VersionPlan, String>,
    /// The version report decided from that analysis.
    pub report: VersionReport,
}

/// Make the release selection ([`Selection`]): analyse the contract against the last
/// release, refuse a guess ([`crate::release::compat::VersionPlan::measured_version`]), and
/// decide the report from what is left ([`report`]).
///
/// ```
/// use majordomus_cli::capability::registry::CapabilityRegistry;
/// use majordomus_cli::release::version::{default_target, select, Version};
/// let dir = tempfile::tempdir().unwrap();
/// let registry = CapabilityRegistry::builder().build().unwrap();
/// let selection = select(dir.path(), &registry, &[]);
/// // the writer's default target is read from this report, so it refuses with its reason
/// let current = Version::parse("0.1.0").unwrap();
/// assert_eq!(
///     default_target(&selection.report, current).unwrap_err(),
///     selection.report.contract_unreadable.clone().unwrap()
/// );
/// ```
pub fn select(
    root: &Path,
    registry: &crate::capability::registry::CapabilityRegistry,
    objects: &[Object],
) -> Selection {
    let plan = super::compat::analyze(root, registry, objects, None).map_err(|e| e.to_string());
    let contract = match &plan {
        Ok(p) => p.measured_version(),
        Err(why) => Err(why.clone()),
    };
    Selection {
        report: report(root, objects, contract),
        plan,
    }
}

/// The version `release bump` raises to when no target is named: the report's `next`, the
/// declared version when nothing would be released — and a refusal, with the report's
/// reason, when the contract could not be measured and so no one decided.
///
/// ```
/// use majordomus_cli::release::model::{DecidedBy, VersionReport};
/// use majordomus_cli::release::version::{default_target, Version};
/// let report = |next: Option<&str>, decided_by, why: Option<&str>| VersionReport {
///     declared: "0.11.0".into(), tool: "0.11.0".into(), agree: true,
///     last_release: Some("0.11.0".into()), bump: "patch".into(),
///     commits_imply: Some("0.11.1".into()), next: next.map(Into::into), decided_by,
///     contract_unreadable: why.map(Into::into), changes: Vec::new() };
/// let current = Version::parse("0.11.0").unwrap();
/// let fix = report(Some("0.11.1"), DecidedBy::ContractAndCommits, None);
/// assert_eq!(default_target(&fix, current).unwrap().to_string(), "0.11.1");
/// let nothing = report(None, DecidedBy::Contract, None);
/// assert_eq!(default_target(&nothing, current), Ok(current));
/// let unread = report(None, DecidedBy::Undecided, Some("no release"));
/// assert_eq!(default_target(&unread, current), Err("no release".into()));
/// ```
pub fn default_target(report: &VersionReport, current: Version) -> Result<Version, String> {
    match (&report.next, report.decided_by) {
        (_, DecidedBy::Undecided) => Err(report
            .contract_unreadable
            .clone()
            .unwrap_or_else(|| "the public contract could not be measured".into())),
        (Some(next), _) => Version::parse(next)
            .ok_or_else(|| format!("the selected version '{next}' is not three numbers")),
        (None, _) => Ok(current),
    }
}

