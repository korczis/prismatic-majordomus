# majordomus-timeout: 300
# majordomus-covers: check
# majordomus-negative: check
# A tracked file a hook regenerates does not refuse a task that never touched it (I1999). An
# adopter (progresus-isir, 0.14.0) had seven tracked files rewritten by a post-checkout hook on
# every checkout, so every task failed `check` on work it never did, and `finish` then refused
# over a handover `check` had not asked for. This case holds:
#
#   1  a path the policy declares under `regenerated:`, with its reason, is the machine's: check
#      names it with the declaration that covers it and passes
#   2  an undeclared path outside the scope still fails, and the finding names both remedies
#   3  a declaration without a reason is refused
#   4  check says beforehand what `finish --outcome completed` refuses over the note, with the
#      command that settles it, and says nothing once a handover is written
#   5  the Rust edit guard gives the declared path the same reading: let through, while an
#      undeclared path no claim covers is refused
#
# Skips itself when there is neither cargo nor MAJORDOMUS_BIN, as the other Rust cases do.
. "$ROOT/test/lib.sh"
command -v jq >/dev/null 2>&1 || skip "jq absent"
RB="$(rust_bin)" || rust_bin_exit $?
export MAJORDOMUS_SHARE="$ROOT/share" MAJORDOMUS_BIN="$RB"

PIDS=""
trap 'for p in $PIDS; do kill "$p" 2>/dev/null || true; done' EXIT

"$MJ" init >/dev/null; "$MJ" update >/dev/null
mkdir -p lib gen other && echo a > lib/a && echo g > gen/a.lock && echo o > other/o
git add -A && git commit -qm base
pol=.ai/repo/policy.yaml
printf '\nregenerated:\n  - path: gen/a.lock\n    reason: rewritten by the post-checkout hook\n' >> "$pol"
git add -A && git commit -qm "the hook's file is declared"
"$MJ" start "the task touches lib only" --scope lib >/dev/null

# ---------------------------------------------------------------- 1. the declared path is the machine's
echo lib >> lib/a
echo rewritten >> gen/a.lock   # the post-checkout hook, not the task
expect_exit 0 "$MJ" check
expect_grep 'INFO +scope +gen/a\.lock .*regenerated by this repository.s own tooling, not by the task: policy regenerated \(gen/a\.lock: rewritten by the post-checkout hook\)'
expect_grep 'OK +scope .*1 touched file\(s\) within scope, and 1 the repository.s own tooling regenerated'
expect_no_grep 'FAIL scope'

# ---------------------------------------------------------------- 2. an undeclared path still fails, naming the remedies
echo o2 >> other/o
expect_exit 10 "$MJ" check
expect_grep 'FAIL scope +other/o .*outside claimed scope \(lib\); settle it: name it in the task.s scope, or stop tracking it \(git rm --cached\)'
expect_grep 'FAIL scope +other/o .*declared once under regenerated: in the policy, with the reason'
expect_no_grep 'FAIL scope +gen/a\.lock'
git checkout -q -- other/o

# ---------------------------------------------------------------- 3. a declaration without a reason is refused
printf '  - path: gen/b.lock\n' >> "$pol"
expect_exit 10 "$MJ" check
expect_grep 'FAIL scope +policy:regenerated\.1 .*declares gen/b\.lock without a reason'
git checkout -q -- "$pol"
git diff --quiet -- "$pol" || { echo "    the policy was not restored"; exit 1; }

# ---------------------------------------------------------------- 4. what finish will refuse over the note, said by check
expect_exit 0 "$MJ" check
expect_grep 'WARN +note +.* finish --outcome completed will refuse: no --note file and no handover for this task'
expect_grep 'reproduce: majordomus handover < note\.md'
printf '# Objective\nthe lib work\n\n# Current State\nlib/a changed\n\n# Next Action\nfinish it\n' \
  | "$MJ" handover >/dev/null
expect_exit 0 "$MJ" check
expect_no_grep 'WARN +note'

# ---------------------------------------------------------------- 5. the edit guard reads it the same way
sed -i.bak 's/^  edits_require_claim: false/  edits_require_claim: true/' "$pol" && rm -f "$pol.bak"
grep -q '^  edits_require_claim: true' "$pol" || { echo "    the fixture's policy did not turn the guard on"; exit 1; }
mkdir -p .ai/repo/mesh
printf 'schema: mesh/v1\nkind: mesh-declaration\nid: majordomus\nenabled: true\n' > .ai/repo/mesh/majordomus.yaml
printf 'multicast:\n  enabled: false\ntrust:\n  policy: tofu\n' >> .ai/repo/mesh/majordomus.yaml
printf 'cooperation:\n  heartbeat_seconds: 1\n  expiry_seconds: 30\n  repository: case-3703\n' >> .ai/repo/mesh/majordomus.yaml
# the server reads the committed declaration, as case 3069's does
git add .ai/repo && git -c core.hooksPath=/dev/null commit -qm "the guard is on and the mesh enabled"
mkdir -p "$T/state" "$T/bin" "$T/elsewhere"
printf '#!/bin/sh\necho "gh: not here in this case" >&2\nexit 4\n' > "$T/bin/gh"
chmod +x "$T/bin/gh"
export PATH="$T/bin:$PATH" XDG_STATE_HOME="$T/state"
R="$(pwd -P)"
( exec "$RB" serve --port 0 --idle 0 --discovery filesystem </dev/null >"$T/serve.log" 2>&1 ) &
PIDS="$PIDS $!"
ready() { [ -n "$(jq -r '.url // empty' .ai/local/state/mcp/server.json 2>/dev/null)" ]; }
i=0; until ready; do i=$((i + 1)); [ "$i" -lt 200 ] || { cat "$T/serve.log"; exit 1; }; sleep 0.2; done
guard() { # <path> -> the guard hook's exit code; stderr in $T/err
  printf '{"session_id":"cc1","tool_name":"Edit","tool_input":{"file_path":"%s"}}' "$1" \
    | (cd "$T/elsewhere" && "$RB" guard hook --provider claude-code) 2>"$T/err"
}
got=0; guard "$R/gen/a.lock" || got=$?
[ "$got" = 0 ] || { echo "    the guard refused the declared regenerated path: exit $got"; cat "$T/err"; exit 1; }
got=0; guard "$R/other/o" || got=$?
[ "$got" = 2 ] || { echo "    the guard let an undeclared, unclaimed path through: exit $got"; cat "$T/err"; exit 1; }
grep -q 'no claim covers other/o' "$T/err" || { echo "    the refusal does not name the path"; cat "$T/err"; exit 1; }

echo "    a declared regenerated path is the machine's in check and in the guard; an undeclared one fails naming both remedies; a reason-less declaration is refused; check warns of finish's note refusal until a handover exists"
